import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const production = process.argv.includes("--production");
const rawApiUrl = (process.env.SAFEHER_PUBLIC_API_URL || "").trim();
let apiBaseUrl = "";

if (production) {
  if (!rawApiUrl) {
    throw new Error("SAFEHER_PUBLIC_API_URL is required for a production frontend build.");
  }
  let parsed;
  try {
    parsed = new URL(rawApiUrl);
  } catch {
    throw new Error("SAFEHER_PUBLIC_API_URL must be a valid HTTPS origin.");
  }
  if (parsed.protocol !== "https:" || parsed.username || parsed.password || parsed.pathname !== "/" || parsed.search || parsed.hash) {
    throw new Error("SAFEHER_PUBLIC_API_URL must be an HTTPS origin without credentials, path, query, or fragment.");
  }
  apiBaseUrl = parsed.origin;
}

const configPath = fileURLToPath(new URL("./runtime-config.js", import.meta.url));
const config = `/* Generated by build-config.mjs. This value is public and must contain no secrets. */\nwindow.SAFEHER_PUBLIC_CONFIG = Object.freeze({ apiBaseUrl: ${JSON.stringify(apiBaseUrl)} });\n`;
await writeFile(configPath, config, "utf8");
process.stdout.write(production ? "Production frontend config generated.\n" : "Local frontend config generated.\n");
